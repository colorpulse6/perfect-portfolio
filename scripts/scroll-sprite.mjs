import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const root = resolve("src/components/scroll")
const names = readdirSync(resolve(root, "tech")).filter(name => name.endsWith(".svg")).sort()
if (names.length !== 21) throw new Error(`Expected 21 icons, got ${names.length}`)
const symbols = names.map(name => {
  const raw = readFileSync(resolve(root, "tech", name), "utf8").trim()
  if (Buffer.byteLength(raw) > 6144 || !/<svg\b[^>]*viewBox="0 0 24 24"/.test(raw) ||
      /<(script|image|foreignObject|style)\b|\bhref\s*=|\bstyle\s*=|url\(|\bon\w+\s*=/i.test(raw)) {
    throw new Error(`Unsafe or malformed icon: ${name}`)
  }
  const inner = raw.replace(/^<svg\b[^>]*>/, "").replace(/<\/svg>$/, "").replace(/<title>.*?<\/title>/s, "")
  if (inner.includes("<svg")) throw new Error(`Nested SVG: ${name}`)
  return `<symbol id="i-${name.slice(0, -4)}" viewBox="0 0 24 24">${inner}</symbol>`
})
const output = `// Generated by scripts/scroll-sprite.mjs from tech/*.svg.\nexport const TECH_SPRITE = ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="position:absolute;width:0;height:0">${symbols.join("")}</svg>`)}\n`
const target = resolve(root, "techSprite.generated.ts")
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) throw new Error("Tech sprite is stale")
} else {
  writeFileSync(target, output)
}
